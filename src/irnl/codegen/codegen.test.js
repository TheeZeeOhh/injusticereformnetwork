import { describe, it, expect } from 'vitest';
import { emitTypeScript, emitRust, emitPython } from './index.js';
import { loadSpec } from '../spec.js';

const program = loadSpec();

describe('IRNL codegen', () => {
  it('emits a do-not-edit banner in every target', () => {
    for (const src of [emitTypeScript(program), emitRust(program), emitPython(program)]) {
      expect(src).toContain('GENERATED BY IRNL — DO NOT EDIT.');
      expect(src).toContain('src/irnl/spec/irn.irn');
    }
  });

  it('emits every entity in every target', () => {
    const ts = emitTypeScript(program);
    const rs = emitRust(program);
    const py = emitPython(program);
    for (const name of Object.keys(program.entities)) {
      expect(ts).toContain(`export interface ${name} {`);
      expect(rs).toContain(`pub struct ${name} {`);
      expect(py).toContain(`class ${name}:`);
    }
  });

  it('keeps Ciphertext distinct from a plain string in all three', () => {
    expect(emitTypeScript(program)).toContain('__ciphertext: unique symbol');
    expect(emitRust(program)).toContain('pub struct Ciphertext(pub String);');
    expect(emitPython(program)).toContain('Ciphertext = NewType("Ciphertext", str)');
  });

  it('carries the same MIN_CELL_SIZE into all three targets', () => {
    expect(emitTypeScript(program)).toContain('export const MIN_CELL_SIZE = 5;');
    expect(emitRust(program)).toContain('pub const MIN_CELL_SIZE: i64 = 5;');
    expect(emitPython(program)).toContain('MIN_CELL_SIZE = 5');
  });

  it('marks quasi-identifiers and PHI in the generated docs', () => {
    const ts = emitTypeScript(program);
    expect(ts).toContain('quasi-identifier — counts toward the k-anonymity floor');
    expect(ts).toContain('PHI — encrypted at rest');
    expect(ts).toContain('AAD-bound to client.id');
  });

  it('renders enums natively per target', () => {
    expect(emitTypeScript(program)).toContain('"health" | "legal" | "part2" | "hrt"');
    expect(emitRust(program)).toContain('pub enum RecordKind {');
    expect(emitPython(program)).toContain('Literal["health", "legal", "part2", "hrt"]');
  });
});
