// codegen/index.js — emit IRNL entities as native types for each stack.
//
// The three emitters live together because they share one type mapping; the
// point of the language is that TS, Rust and Python cannot disagree about a
// shape, and splitting the mapping across files is how that disagreement
// starts. Add a target by adding an emitter here and a row to TYPE_MAP.
//
// Emitted files carry a generated-by banner and are NOT hand-edited: the CLI
// (`node src/irnl/cli.js build`) rewrites them from src/irnl/spec/irn.irn.
//
// Pure module — returns strings, writes nothing.

const BANNER_LINES = [
  'GENERATED BY IRNL — DO NOT EDIT.',
  'Source: src/irnl/spec/irn.irn',
  'Regenerate: node src/irnl/cli.js build'
];

const TYPE_MAP = {
  Ulid: { ts: 'Ulid', rust: 'Ulid', py: 'Ulid' },
  Text: { ts: 'string', rust: 'String', py: 'str' },
  Int: { ts: 'number', rust: 'i64', py: 'int' },
  Bool: { ts: 'boolean', rust: 'bool', py: 'bool' },
  Timestamp: { ts: 'string', rust: 'String', py: 'str' },
  // Ciphertext is deliberately a distinct alias in every target: it must never
  // be interchangeable with a plaintext string at a call site.
  Ciphertext: { ts: 'Ciphertext', rust: 'Ciphertext', py: 'Ciphertext' }
};

const banner = (comment) => BANNER_LINES.map((l) => `${comment} ${l}`).join('\n');

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();

/** Field type in a target language. Enum/Ref resolve per-target. */
function typeFor(field, target, entityName) {
  if (field.type === 'Enum') {
    const variants = field.typeArgs.map(String);
    if (target === 'ts') return variants.map((v) => JSON.stringify(v)).join(' | ');
    if (target === 'py') return `Literal[${variants.map((v) => JSON.stringify(v)).join(', ')}]`;
    return `${pascal(entityName)}${pascal(field.name)}`; // rust: a named enum
  }
  if (field.type === 'Ref') {
    // A reference is stored as the target's identity value, not an inlined
    // object — records are encrypted at rest and joined on id.
    return TYPE_MAP.Ulid[target];
  }
  return TYPE_MAP[field.type]?.[target] ?? (target === 'ts' ? 'unknown' : 'String');
}

/** Doc comment describing the annotations on a field. */
function fieldNote(field) {
  const notes = [];
  if (field.isIdentity) notes.push('identity');
  if (field.isPhi) notes.push('PHI — encrypted at rest');
  if (field.isPii) notes.push('PII');
  if (field.isQuasiIdentifier) notes.push('quasi-identifier — counts toward the k-anonymity floor');
  if (field.aad) notes.push(`AAD-bound to ${field.aad}`);
  return notes.join('; ');
}

/**
 * TypeScript declarations for the app/front end.
 * @param {object} program
 * @returns {string}
 */
export function emitTypeScript(program) {
  const out = [banner('//'), ''];
  out.push('export type Ulid = string;');
  out.push('/** Base64 AES-256-GCM ciphertext. Never assign a plaintext string to this. */');
  out.push('export type Ciphertext = string & { readonly __ciphertext: unique symbol };');
  out.push('');
  for (const entity of Object.values(program.entities)) {
    out.push(`export interface ${entity.name} {`);
    for (const f of entity.fields) {
      const note = fieldNote(f);
      if (note) out.push(`  /** ${note} */`);
      out.push(`  ${f.name}: ${typeFor(f, 'ts', entity.name)};`);
    }
    out.push('}');
    out.push('');
  }
  // Constants the front end would otherwise hardcode.
  const min = program.policies?.aggregation?.settings?.min_cell_size;
  if (typeof min === 'number') {
    out.push('/** k-anonymity floor. Cells below this are suppressed, never rounded. */');
    out.push(`export const MIN_CELL_SIZE = ${min};`);
    out.push('');
  }
  return out.join('\n');
}

/**
 * Rust structs for the Tauri shell.
 * @param {object} program
 * @returns {string}
 */
export function emitRust(program) {
  const out = [banner('//'), ''];
  out.push('#![allow(dead_code)]');
  out.push('');
  out.push('pub type Ulid = String;');
  out.push('/// Base64 AES-256-GCM ciphertext. Distinct from String on purpose.');
  out.push('#[derive(Debug, Clone, PartialEq, Eq)]');
  out.push('pub struct Ciphertext(pub String);');
  out.push('');
  for (const entity of Object.values(program.entities)) {
    // Named enums first — Rust has no inline unions.
    for (const f of entity.fields) {
      if (f.type !== 'Enum') continue;
      const enumName = `${pascal(entity.name)}${pascal(f.name)}`;
      out.push('#[derive(Debug, Clone, PartialEq, Eq)]');
      out.push(`pub enum ${enumName} {`);
      for (const v of f.typeArgs) out.push(`    ${pascal(String(v))},`);
      out.push('}');
      out.push('');
    }
    out.push('#[derive(Debug, Clone)]');
    out.push(`pub struct ${entity.name} {`);
    for (const f of entity.fields) {
      const note = fieldNote(f);
      if (note) out.push(`    /// ${note}`);
      out.push(`    pub ${snake(f.name)}: ${typeFor(f, 'rust', entity.name)},`);
    }
    out.push('}');
    out.push('');
  }
  const min = program.policies?.aggregation?.settings?.min_cell_size;
  if (typeof min === 'number') {
    out.push('/// k-anonymity floor. Cells below this are suppressed, never rounded.');
    out.push(`pub const MIN_CELL_SIZE: i64 = ${min};`);
    out.push('');
  }
  return out.join('\n');
}

/**
 * Python dataclasses for Zee Zee / Amina / the hive tooling.
 * @param {object} program
 * @returns {string}
 */
export function emitPython(program) {
  const out = [banner('#'), ''];
  out.push('from __future__ import annotations');
  out.push('from dataclasses import dataclass');
  out.push('from typing import Literal, NewType');
  out.push('');
  out.push('Ulid = NewType("Ulid", str)');
  out.push('# Base64 AES-256-GCM ciphertext. Distinct from str on purpose.');
  out.push('Ciphertext = NewType("Ciphertext", str)');
  out.push('');
  for (const entity of Object.values(program.entities)) {
    out.push('@dataclass(frozen=True)');
    out.push(`class ${entity.name}:`);
    for (const f of entity.fields) {
      const note = fieldNote(f);
      if (note) out.push(`    # ${note}`);
      out.push(`    ${snake(f.name)}: ${typeFor(f, 'py', entity.name)}`);
    }
    out.push('');
  }
  const min = program.policies?.aggregation?.settings?.min_cell_size;
  if (typeof min === 'number') {
    out.push('# k-anonymity floor. Cells below this are suppressed, never rounded.');
    out.push(`MIN_CELL_SIZE = ${min}`);
    out.push('');
  }
  return out.join('\n');
}

export const TARGETS = {
  typescript: { emit: emitTypeScript, path: 'src/types/irn.generated.ts' },
  rust: { emit: emitRust, path: 'src-tauri/src/irn_generated.rs' },
  python: { emit: emitPython, path: 'src/irnl/generated/irn_types.py' }
};
